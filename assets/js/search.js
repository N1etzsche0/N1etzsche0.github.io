(() => {
  const overlay = document.getElementById('search-overlay');
  const input = document.getElementById('search-input');
  const results = document.getElementById('search-results');
  const button = document.getElementById('search-btn');
  if (!overlay || !input || !results || !button) return;

  const template = id => document.getElementById(`search-tpl-${id}`)?.innerHTML || '';
  const base = new URL(document.documentElement.dataset.baseUrl || '/', location.origin);
  let loader;
  let sequence = 0;
  let previousFocus;
  const visible = () => overlay.classList.contains('is-visible');

  function loadPagefind() {
    loader ??= import(new URL('pagefind/pagefind.js', base).href)
      .then(async pagefind => {
        await pagefind.options({ baseUrl: base.pathname });
        await pagefind.init();
        return pagefind;
      })
      .catch(error => {
        loader = null;
        if (visible()) results.innerHTML = template('unavailable');
        throw error;
      });
    return loader;
  }

  function open() {
    previousFocus = document.activeElement;
    overlay.inert = false;
    overlay.classList.add('is-visible');
    document.body.classList.add('search-open');
    overlay.setAttribute('aria-hidden', 'false');
    button.setAttribute('aria-expanded', 'true');
    input.focus();
    // The index is fetched only when the visitor opens search.
    void loadPagefind().catch(() => {});
  }

  function close() {
    sequence++;
    overlay.classList.remove('is-visible');
    document.body.classList.remove('search-open');
    button.setAttribute('aria-expanded', 'false');
    input.value = '';
    results.innerHTML = template('empty');
    previousFocus?.focus();
    overlay.inert = true;
    overlay.setAttribute('aria-hidden', 'true');
  }

  button.addEventListener('click', open);
  document.getElementById('search-close')?.addEventListener('click', close);
  overlay.addEventListener('click', event => { if (event.target === overlay) close(); });
  document.addEventListener('keydown', event => {
    if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === 'k') {
      event.preventDefault();
      visible() ? close() : open();
    }
    if (!visible()) return;
    if (event.key === 'Escape') close();
    if (event.key === 'Tab') {
      const controls = [...overlay.querySelectorAll('input, button, a')];
      const first = controls[0];
      const last = controls.at(-1);
      if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
      else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
    }
  });

  const escape = text => {
    const element = document.createElement('span');
    element.textContent = text || '';
    return element.innerHTML;
  };

  function render(hits) {
    results.replaceChildren();
    if (!hits.length) { results.innerHTML = template('no-results'); return; }
    for (const item of hits) {
      const url = new URL(item.url, base);
      if (url.origin !== location.origin) continue;
      const link = document.createElement('a');
      link.className = 'search-hit';
      link.href = url.href;
      // Excerpts are generated by our local Pagefind build, including <mark>.
      link.innerHTML = `<div class="search-hit__title">${escape(item.meta.title || item.url)}</div>` +
        `<div class="search-hit__meta">${escape(item.meta.date)}</div>` +
        `<div class="search-hit__excerpt">${item.excerpt || ''}</div>`;
      results.append(link);
    }
  }

  input.addEventListener('input', async () => {
    const current = ++sequence;
    const query = input.value.trim();
    if (!query) { results.innerHTML = template('empty'); return; }
    try {
      const pagefind = await loadPagefind();
      const search = await pagefind.debouncedSearch(query, {}, 200);
      if (!search || current !== sequence || !visible()) return;
      const hits = await Promise.all(search.results.slice(0, 10).map(result => result.data()));
      if (current === sequence && visible()) render(hits);
    } catch { /* The loader renders a localized unavailable message. */ }
  });
})();
